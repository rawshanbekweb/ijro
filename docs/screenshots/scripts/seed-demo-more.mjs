const API = process.env.API_URL ?? 'http://localhost:3000/api'
const PAROL = 'Demo12345'

async function req(method, path, token, body) {
  const res = await fetch(API + path, {
    method,
    headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  })
  const text = await res.text()
  if (!res.ok) throw new Error(`${method} ${path} -> ${res.status} ${text}`)
  return text ? JSON.parse(text) : null
}
const tokens = {}
const tok = async (l, p = PAROL) => (tokens[l] ??= (await req('POST', '/auth/login', null, { login: l, parol: p })).accessToken)

const admin = await tok(process.env.ADMIN_LOGIN ?? 'superadmin', process.env.ADMIN_PAROL ?? 'Admin12345')
tokens.admin = admin
const tasks = await req('GET', '/tasks', admin)
const byTitle = (start) => {
  const t = tasks.find((x) => x.sarlavha.startsWith(start))
  if (!t) throw new Error('Topshiriq topilmadi: ' + start)
  return t
}
